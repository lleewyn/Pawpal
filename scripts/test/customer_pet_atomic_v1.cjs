const fs=require('node:fs'),{spawnSync}=require('node:child_process');
const {state}=require('./customer_completion_helpers.cjs');
const ddl=fs.readFileSync('scripts/database/v1/059_customer_portal_pet.sql','utf8').replace(/^BEGIN;|^COMMIT;|^NOTIFY.*$/gm,'');
const access=fs.readFileSync('scripts/database/v1/060_customer_pet_diary_access.sql','utf8').replace(/^BEGIN;|^COMMIT;|^NOTIFY.*$/gm,'');
const q=`BEGIN; ${ddl} ${access}
DO $$ DECLARE uid uuid:=gen_random_uuid(); cid uuid:=gen_random_uuid(); pid uuid:=gen_random_uuid(); breed uuid; v jsonb; stamp timestamptz; rejected boolean;
 other_uid uuid:=gen_random_uuid(); other_cid uuid:=gen_random_uuid();
BEGIN
 INSERT INTO auth.users(id) VALUES(uid);
 INSERT INTO auth.users(id) VALUES(other_uid);
 INSERT INTO public.customer(id,auth_user_id,customer_code,customer_status) VALUES(cid,uid,'TEST-'||cid,'active');
 INSERT INTO public.customer(id,auth_user_id,customer_code,customer_status) VALUES(other_cid,other_uid,'TEST-'||other_cid,'active');
 SELECT b.id INTO breed FROM public.pet_breed b JOIN public.pet_species s ON s.id=b.species_id WHERE b.is_active AND s.is_active LIMIT 1;
 IF breed IS NULL THEN RAISE EXCEPTION 'Missing stage taxonomy'; END IF;
 PERFORM set_config('request.jwt.claim.sub',uid::text,true);
 v:=jsonb_build_object('pet_name','Atomic fixture','breed_id',breed,'gender','nam');
 PERFORM public.save_own_pet(pid,null,v,5);
 SELECT updated_at INTO stamp FROM public.pet_profile WHERE id=pid;
 PERFORM public.save_own_pet(pid,stamp,v,5);
 IF (SELECT count(*) FROM public.pet_weight_history WHERE pet_id=pid)<>1 THEN RAISE EXCEPTION 'Duplicate weight'; END IF;
 rejected:=false; BEGIN PERFORM public.save_own_pet(pid,stamp-interval '1 second',v,6); EXCEPTION WHEN SQLSTATE 'PT409' THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Stale write accepted'; END IF;
 SELECT updated_at INTO stamp FROM public.pet_profile WHERE id=pid;
 rejected:=false; BEGIN PERFORM public.save_own_pet(pid,stamp,v||'{"pet_name":"Invalid write"}',-1); EXCEPTION WHEN invalid_parameter_value THEN rejected:=true; END;
 IF NOT rejected OR (SELECT pet_name FROM public.pet_profile WHERE id=pid)<>'Atomic fixture' THEN RAISE EXCEPTION 'Invalid write persisted'; END IF;
 PERFORM public.save_own_pet(pid,stamp,v,6);
 IF (SELECT count(*) FROM public.pet_weight_history WHERE pet_id=pid)<>2 THEN RAISE EXCEPTION 'Changed weight missing'; END IF;
 INSERT INTO public.appointment(id,appointment_code,customer_id,pet_id,scheduled_start_at,scheduled_end_at,appointment_status)
 VALUES(pid,'TEST-'||pid,cid,pid,now(),now()+interval '1 hour','in_progress');
 INSERT INTO public.care_log(id,appointment_id,action_name_snapshot,description) VALUES(pid,pid,'Care fixture','Private care note');
 PERFORM set_config('role','authenticated',true);
 IF (SELECT count(*) FROM public.care_log WHERE id=pid)<>1 THEN RAISE EXCEPTION 'Owner diary unreadable'; END IF;
 PERFORM public.change_own_pet_status(pid,(SELECT updated_at FROM public.pet_profile WHERE id=pid),false);
 IF (SELECT status FROM public.pet_profile WHERE id=pid)<>'inactive' THEN RAISE EXCEPTION 'Archive failed'; END IF;
 PERFORM public.change_own_pet_status(pid,(SELECT updated_at FROM public.pet_profile WHERE id=pid),true);
 PERFORM set_config('request.jwt.claim.sub',other_uid::text,true);
 IF EXISTS(SELECT 1 FROM public.care_log WHERE id=pid) OR EXISTS(SELECT 1 FROM public.appointment WHERE id=pid) THEN RAISE EXCEPTION 'Foreign customer data leaked'; END IF;
 rejected:=false; BEGIN PERFORM public.change_own_pet_status(pid,stamp,false); EXCEPTION WHEN insufficient_privilege THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Foreign archive allowed'; END IF;
 PERFORM set_config('role','supabase_admin',true);
 PERFORM set_config('request.jwt.claim.sub',uid::text,true);
 UPDATE auth.users SET banned_until=now()+interval '1 day' WHERE id=uid;
 rejected:=false; BEGIN PERFORM public.change_own_pet_status(pid,stamp,false); EXCEPTION WHEN insufficient_privilege THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Banned identity accepted'; END IF;
 UPDATE auth.users SET banned_until=null WHERE id=uid;
 UPDATE public.customer SET auth_user_id=null WHERE id=cid;
 rejected:=false; BEGIN PERFORM public.save_own_pet(pid,stamp,v,7); EXCEPTION WHEN insufficient_privilege THEN rejected:=true; END;
 IF NOT rejected THEN RAISE EXCEPTION 'Foreign identity accepted'; END IF;
END $$; ROLLBACK;`;
const r=spawnSync('docker',['exec','-i','supabase-db','psql','-X','-q','-U','supabase_admin','-d',state.stage,'-v','ON_ERROR_STOP=1'],{input:q,encoding:'utf8',windowsHide:true});
if(r.status!==0)throw Error(r.stderr);
console.log('PASS isolated pet atomic create/update, unchanged weight deduplication, changed weight history, stale revision and invalid/foreign write rejection; fixtures rolled back.');
