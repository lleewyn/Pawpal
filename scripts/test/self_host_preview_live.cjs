// Browser integration for the isolated preview. Credentials never enter logs.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const assert=require('node:assert/strict');
const {createClient}=require('@supabase/supabase-js');
const envPath=process.argv[2],playwrightPath=process.argv[3];
if(!envPath||!path.isAbsolute(envPath)||!playwrightPath)throw Error('Pass local infra .env and Playwright package path');
const env=require('dotenv').parse(fs.readFileSync(envPath));
if(env.SUPABASE_PUBLIC_URL!=='http://localhost:8000')throw Error('Local-only test');
const {chromium}=require(playwrightPath);
const adminFile=fs.readFileSync(path.join(path.dirname(envPath),'PAWPAL-ADMIN.private.txt'),'utf8');
const email=adminFile.match(/^Email: (.+)$/m)[1],password=adminFile.match(/^Password: (.+)$/m)[1];
const service=createClient(env.SUPABASE_PUBLIC_URL,env.SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
const phone='09'+String(crypto.randomInt(100000000)).padStart(8,'0');
const label='Kiểm tra local '+crypto.randomUUID().slice(0,8);
const captureDir=path.join(path.dirname(envPath),'verification');fs.mkdirSync(captureDir,{recursive:true});
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage();page.setDefaultTimeout(20000);
 const errors=[],cloud=[];
 page.on('response',r=>{if(r.status()>=400&&new URL(r.url()).pathname.startsWith('/rest/v1/'))errors.push(r.status()+' '+new URL(r.url()).pathname);});
 page.on('request',r=>{if(new URL(r.url()).hostname.endsWith('.supabase.co'))cloud.push(new URL(r.url()).hostname);});
 try{
  await page.goto('http://localhost:3001/admin/login');
  await page.locator('#inputAdminEmail').fill(email);await page.locator('#inputAdminPassword').fill(password);
  await page.locator('#btnSubmitAdminLogin').click();await page.waitForURL('**/admin#tab-list');
  await page.waitForFunction(()=>window.PawpalCustomers?.state.hasLoadedCustomers);
  await page.waitForFunction(()=>window.PawpalCustomers?.state.pawpointLoadStatus==='loaded');
  console.log('PASS Admin login, customer list and empty Pawpoint ledger settle');
  await page.locator('#btnOpenAddCustomerModal').click();
  await page.locator('#quickAddName').fill(label);await page.locator('#quickAddPhone').fill(phone);
  await page.locator('#quickAddPetName').fill(label+' pet');await page.locator('#quickAddPetWeight').fill('4.2');
  await page.locator('#btnSubmitAddCustomer').click();
  await page.locator('#modalAddCustomer').waitFor({state:'hidden'});
  await page.reload();await page.getByText(label,{exact:true}).first().waitFor();
  await page.screenshot({path:path.join(captureDir,'customers.png'),fullPage:true});
  console.log('PASS UI customer and pet creation, customer reload');
  const customerRow=await service.from('customer').select('id').eq('phone_main',phone).single();
  if(customerRow.error)throw Error(customerRow.error.message);
  const customerId=customerRow.data.id;
  await page.getByText(label,{exact:true}).first().click();
  await page.locator('#btnOpenEditProfileModal').click();
  await page.locator('#editCustFullName').fill(label+' updated');
  await page.locator('#editCustTier').selectOption('SILVER');
  await page.locator('#btnSubmitEditCustomer').click();
  await page.locator('#modalEditCustomer').waitFor({state:'hidden'});
  const edited=await service.from('customer_profile').select('full_name').eq('customer_id',customerId).single();
  assert.equal(edited.data?.full_name,label+' updated');
  const membership=await service.from('customer_membership').select('total_paw_points').eq('customer_id',customerId).single();
  assert.equal(membership.data?.total_paw_points,300);
  const audit=await service.from('audit_log').select('staff_id,staff:staff_id(email)').eq('entity_id',customerId).single();
  assert.equal(audit.data?.staff.email,email);
  console.log('PASS customer edit, membership upsert and real staff audit actor');
  await page.goto('http://localhost:3001/admin#tab-pet-list');
  await page.getByText(label+' pet',{exact:true}).first().waitFor();
  await page.screenshot({path:path.join(captureDir,'pets.png'),fullPage:true});
  console.log('PASS pet list reads saved pet');
  await page.locator('#btnOpenAddPetModal').click();
  await page.locator('#newPetOwnerInput').fill(phone);
  await page.locator('#newPetOwnerDropdown .autocomplete-item').first().click();
  await page.locator('#newPetName').fill(label+' separate pet');
  await page.locator('#newPetBreed').fill('Poodle');
  await page.locator('#newPetWeight').fill('2.8');
  await page.locator('#newPetName').click();
  await page.locator('#btnSubmitAddPet').click();
  await page.locator('#modalAddPet').waitFor({state:'hidden'});
  await page.getByText(label+' separate pet',{exact:true}).first().waitFor();
  const separate=await service.from('pet_profile').select('id,weight,customer_id').eq('pet_name',label+' separate pet').single();
  assert.equal(separate.data?.customer_id,customerId);assert.equal(separate.data?.weight,2.8);
  const weight=await service.from('pet_weight_history').select('weight').eq('pet_id',separate.data.id).single();
  assert.equal(weight.data?.weight,2.8);
  console.log('PASS separate pet creation with owner autocomplete and weight history');
  await page.getByText(label+' separate pet',{exact:true}).first().click();
  await page.locator('#btnOpenEditPetModal').click();
  await page.locator('#editPetName').fill(label+' edited pet');
  await page.locator('#btnSubmitEditPetProfile').click();
  await page.locator('#modalEditPetProfile').waitFor({state:'hidden'});
  const petEdit=await service.from('pet_profile').select('pet_name').eq('id',separate.data.id).single();
  assert.equal(petEdit.data?.pet_name,label+' edited pet');
  await page.reload();await page.getByText(label+' edited pet',{exact:true}).first().waitFor();
  console.log('PASS pet edit and reload');
  await page.goto('http://localhost:3001/admin#tab-pet-list');
  const petRow=()=>page.locator('tr').filter({hasText:label+' edited pet'});
  await petRow().locator('.btn-action-more').scrollIntoViewIfNeeded();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await petRow().locator('.btn-action-more').click();
  await page.locator('[data-action="archive"]').click();
  await page.locator('#btnAcceptPetConfirm').click();
  await page.waitForFunction(id=>Object.values(window.PawpalPets.state.petsData).some(p=>p.rawId===id&&p.status==='Lưu trữ'),separate.data.id);
  assert.equal((await service.from('pet_profile').select('status').eq('id',separate.data.id).single()).data.status,'INACTIVE');
  await petRow().locator('.btn-action-more').click();
  await page.locator('[data-action="restore"]').click();
  await page.waitForFunction(id=>Object.values(window.PawpalPets.state.petsData).some(p=>p.rawId===id&&p.status!=='Lưu trữ'),separate.data.id);
  assert.equal((await service.from('pet_profile').select('status').eq('id',separate.data.id).single()).data.status,'dang_hoat_dong');
  console.log('PASS pet archive and restore');
  await page.goto('http://localhost:3001/admin#tab-list');
  const ownerRow=()=>page.locator('tr').filter({hasText:label+' updated'});
  for(const locked of [true,false]) {
   await ownerRow().locator('.btn-action-more').scrollIntoViewIfNeeded();
   await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
   await ownerRow().locator('.btn-action-more').click();
   await page.locator('#customerGlobalActionDropdown [data-action="toggle-lock"]').click();
   await page.locator('#btnAcceptCustConfirm').click();
   await page.waitForFunction(({id,locked})=>Object.values(window.PawpalCustomers.state.customerDatabase).some(c=>c.dbId===id&&(c.status==='LOCKED')===locked),{id:customerId,locked});
   assert.equal((await service.from('customer').select('account_status').eq('id',customerId).single()).data.account_status,locked?'da_khoa':'dang_hoat_dong');
  }
  console.log('PASS customer lock and unlock');
  await page.getByText(label+' updated',{exact:true}).first().click();
  await page.locator('[data-drawertab="dtab-pets"]').click();
  await page.locator('.pet-detail-card').filter({hasText:label+' edited pet'}).locator('.btn-pet-delete').click();
  await page.locator('#btnAcceptCustConfirm').click();
  await page.waitForFunction(name=>!document.querySelector('#dtab-pets')?.textContent.includes(name),label+' edited pet');
  assert.equal((await service.from('pet_profile').select('id').eq('id',separate.data.id)).data.length,0);
  assert.equal((await service.from('pet_weight_history').select('id').eq('pet_id',separate.data.id)).data.length,0);
  console.log('PASS pet deletion from owner profile and weight-history cascade');
  assert.deepEqual(errors,[]);assert.deepEqual(cloud,[]);
  console.log('PASS no REST errors or Cloud requests');
 }finally{
  // Clean by this run's unique random phone, independent of page state.
  const record=await service.from('customer').select('id').eq('phone_main',phone).maybeSingle();
  if(record.data)await service.from('audit_log').delete().eq('entity_id',record.data.id);
  const cleanup=await service.from('customer').delete().eq('phone_main',phone);
  await browser.close();if(cleanup.error)throw Error('Test fixture cleanup failed');
 }
})().catch(e=>{console.error(e.message);process.exitCode=1;});
