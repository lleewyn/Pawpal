// One synthetic pet, synthetic actors, no COMMIT. This tests RPC/RLS, not HTTP Auth/UI.
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const fs=require('node:fs'),path=require('node:path');
const {connect}=require('../database/v1/service_import_connection.cjs');
if(!process.argv.includes('--cloud')){console.log('Use --cloud for the rollback-only pet integration check. No network used.');process.exit(0);}
(async()=>{
 const db=await connect();let queries=0;
 const report={environment:'Supabase Cloud cpzuvaplseielhgcnqrn',timestamp:new Date().toISOString(),scope:'Pet RPC/RLS; synthetic actors; transaction always rolled back; no Logs',checks:[]};
 const q=async(sql,args)=>{queries++;return db.query(sql,args);};
 const actor=async(id,role='authenticated')=>{await q('RESET ROLE');await q("SELECT set_config('request.jwt.claim.sub',$1,true),set_config('request.jwt.claim.role',$2,true)",[id,role]);await q(role==='anon'?'SET LOCAL ROLE anon':'SET LOCAL ROLE authenticated');};
 const denied=async(fn,codes)=>{await q('SAVEPOINT expected_denial');let failure;try{await fn();}catch(e){failure=e;}await q('ROLLBACK TO SAVEPOINT expected_denial');await q('RELEASE SAVEPOINT expected_denial');assert.ok(failure,'Expected rejection');assert.ok(codes.includes(failure.code),'Unexpected SQLSTATE '+failure.code);};
 const pass=name=>report.checks.push({name,status:'PASS'});
 try{
  await q("BEGIN;SET LOCAL statement_timeout='8s';SET LOCAL lock_timeout='3s'");
  const a=randomUUID(),b=randomUUID(),sa=randomUUID(),staff=randomUUID(),ca=randomUUID(),cb=randomUUID(),pet=randomUUID();
  report.fixtureIds={customerA:ca,customerB:cb,pet};
  await q('INSERT INTO auth.users(id) VALUES($1),($2),($3)',[a,b,sa]);
  await q("INSERT INTO public.customer(id,auth_user_id,customer_code) VALUES($1,$2,$3),($4,$5,$6)",[ca,a,'E2E-PET-A-'+ca,cb,b,'E2E-PET-B-'+cb]);
  await q("INSERT INTO public.customer_profile(customer_id,full_name) VALUES($1,'E2E Pet A'),($2,'E2E Pet B') ON CONFLICT(customer_id) DO UPDATE SET full_name=excluded.full_name",[ca,cb]);
  await q("INSERT INTO public.staff(id,auth_user_id,full_name,job_title,employment_status,must_change_password) VALUES($1,$2,'E2E Pet Admin','QA','active',false)",[staff,sa]);
  await q("INSERT INTO public.staff_role(staff_id,role_code) VALUES($1,'ADMIN')",[staff]);
  const breed=(await q('SELECT b.id FROM public.pet_breed b JOIN public.pet_species s ON s.id=b.species_id WHERE b.is_active AND s.is_active ORDER BY b.id LIMIT 1')).rows[0]?.id;
  assert.ok(breed,'Active breed required');
  const values={customer_id:cb,pet_name:'E2E Pet Created',breed_id:breed,gender:'nam',safety_note:'E2E safety',allergy:'E2E allergy',routine:'E2E routine'};
  await actor(a);
  await q('SELECT public.save_own_pet($1,NULL,$2::jsonb,5)',[pet,JSON.stringify(values)]);
  let row=(await q('SELECT id,customer_id,pet_name,safety_note,allergy,routine,updated_at::text FROM public.pet_profile WHERE id=$1',[pet])).rows[0];
  assert.equal(row.customer_id,ca);assert.equal(row.pet_name,values.pet_name);
  pass('User creates one pet; server derives owner A despite forged customer_id B');
  await denied(()=>q('SELECT public.save_own_pet($1,NULL,$2::jsonb,5)',[pet,JSON.stringify(values)]),['PT409']);
  assert.equal(Number((await q('SELECT count(*) n FROM public.pet_profile WHERE id=$1',[pet])).rows[0].n),1);
  pass('Retry with same create ID cannot duplicate pet');
  await q('SELECT public.save_own_pet($1,$2,$3::jsonb,NULL)',[pet,row.updated_at,JSON.stringify({...values,pet_name:'E2E User Edited'})]);
  await actor(sa);
  row=(await q('SELECT id,customer_id,pet_name,safety_note,allergy,routine,updated_at::text FROM public.pet_profile WHERE id=$1',[pet])).rows[0];
  assert.equal(row.pet_name,'E2E User Edited');assert.equal(row.customer_id,ca);
  assert.equal(row.safety_note,'E2E safety');assert.equal(row.allergy,'E2E allergy');assert.equal(row.routine,'E2E routine');
  pass('Admin reads exact owner and independent fields after User update');
  await denied(()=>q('SELECT public.update_customer_pet($1,$2,$3,$4,$5,NULL,NULL,NULL,NULL)',[cb,pet,row.updated_at,'E2E Wrong Owner',breed]),['P0002']);
  pass('Admin customer-scoped edit rejects mismatched customer/pet relation');
  await q("SELECT public.update_customer_pet($1,$2,$3,'E2E Admin Edited',$4,NULL,'E2E admin safety','E2E admin allergy','E2E admin routine')",[ca,pet,row.updated_at,breed]);
  await actor(a);
  row=(await q('SELECT id,customer_id,pet_name,safety_note,allergy,routine,updated_at::text FROM public.pet_profile WHERE id=$1',[pet])).rows[0];
  assert.equal(row.pet_name,'E2E Admin Edited');assert.equal(row.safety_note,'E2E admin safety');assert.equal(row.allergy,'E2E admin allergy');
  pass('User reads Admin edits from same pet ID');
  await denied(()=>q('SELECT public.save_own_pet($1,$2,$3::jsonb,0)',[pet,row.updated_at,JSON.stringify(values)]),['22023']);
  await denied(()=>q('SELECT public.save_own_pet($1,$2,$3::jsonb,5)',[pet,'2000-01-01T00:00:00Z',JSON.stringify(values)]),['PT409']);
  pass('Invalid weight and stale version rejected without partial update');
  await q('SELECT public.change_own_pet_status($1,$2,false)',[pet,row.updated_at]);
  await actor(sa);
  row=(await q('SELECT status,updated_at::text FROM public.pet_profile WHERE id=$1',[pet])).rows[0];
  assert.equal(row.status,'inactive');
  pass('User archive is visible to Admin without deleting pet');
  await q('SELECT public.save_admin_pet($1,$2,$3::jsonb,NULL)',[pet,row.updated_at,JSON.stringify({customer_id:ca,breed_id:breed,pet_name:'E2E Admin Restored',gender:'male',status:'active'})]);
  await actor(a);
  row=(await q('SELECT id,customer_id,status,pet_name,updated_at::text FROM public.pet_profile WHERE id=$1',[pet])).rows[0];
  assert.equal(row.status,'active');assert.equal(row.pet_name,'E2E Admin Restored');assert.equal(row.customer_id,ca);
  pass('Admin restore is visible to User and preserves ownership');
  assert.equal(Number((await q('SELECT count(*) n FROM public.pet_weight_history WHERE pet_id=$1',[pet])).rows[0].n),1);
  pass('Name/status updates with null weight do not duplicate weight history');
  await actor(b);
  let hidden=false;await q('SAVEPOINT read_scope');
  try{hidden=(await q('SELECT id FROM public.pet_profile WHERE id=$1',[pet])).rows.length===0;}catch(e){assert.equal(e.code,'42501');hidden=true;await q('ROLLBACK TO SAVEPOINT read_scope');}
  await q('RELEASE SAVEPOINT read_scope');assert.ok(hidden);
  await denied(()=>q('SELECT public.save_own_pet($1,$2,$3::jsonb,5)',[pet,row.updated_at,JSON.stringify(values)]),['42501']);
  await denied(()=>q('SELECT public.change_own_pet_status($1,$2,false)',[pet,row.updated_at]),['42501']);
  pass('B cannot read, edit or archive A pet using its ID');
  await actor('','anon');await denied(()=>q('SELECT public.save_own_pet($1,NULL,$2::jsonb,5)',[pet,JSON.stringify(values)]),['42501']);
  pass('Guest cannot invoke private pet write RPC');
  await q('RESET ROLE');
  assert.equal((await q('SELECT pet_name FROM public.pet_profile WHERE id=$1',[pet])).rows[0].pet_name,'E2E Admin Restored');
  pass('Denied operations leave the pet unchanged');
  await q('ROLLBACK');
  const remains=(await q('SELECT EXISTS(SELECT 1 FROM public.pet_profile WHERE id=$1) OR EXISTS(SELECT 1 FROM public.customer WHERE id=ANY($2::uuid[])) OR EXISTS(SELECT 1 FROM auth.users WHERE id=ANY($3::uuid[])) remains',[pet,[ca,cb],[a,b,sa]])).rows[0].remains;
  assert.equal(remains,false);pass('Rollback removed all synthetic pet/customer/auth fixtures');
  report.status='PASS';report.queries=queries;
  const file=path.resolve('docs/verification/sync/pets-cloud-rollback.txt');fs.mkdirSync(path.dirname(file),{recursive:true});fs.writeFileSync(file,JSON.stringify(report,null,2)+'\n');
  console.log('PASS',report.checks.length,'pet RPC/RLS assertions;',queries,'bounded SQL statements; all fixtures rolled back. Not HTTP/UI E2E.');
 }catch(e){await db.query('ROLLBACK').catch(()=>{});console.error('Pet integration failed:',e.code||'',e.message);process.exitCode=1;}finally{await db.end();}
})().catch(e=>{console.error(e.code||'connection_failed');process.exitCode=1;});
